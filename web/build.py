#!/usr/bin/env python3
"""Build the browser calculator from packages/npm/lib and copy it to every target.

Targets: packages/hf-space (static Space), packages/docker/public (served by
server.js) and extensions/shared (popup, no external links).
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

WEB = Path(__file__).resolve().parent
ROOT = WEB.parent
SITE_LINK = '<a href="https://uaegoldprices.ae/">سعر الذهب اليوم في الامارات</a>'


def gold_js() -> str:
    src = (ROOT / "packages/npm/lib/index.js").read_text(encoding="utf-8")
    src = src.replace("'use strict';\n", "", 1)
    src = re.sub(r"module\.exports = \{", "root.GoldCalc = Object.freeze({", src)
    src = src.rstrip()
    assert src.endswith("};"), "unexpected end of lib/index.js"
    src = src[:-2] + "});"
    return ("/* Generated by web/build.py from packages/npm/lib/index.js. Do not edit. */\n"
            "(function (root) {\n'use strict';\n" + src + "\n})(typeof self !== 'undefined' ? self : this);\n")


def page(popup: bool) -> str:
    body = (WEB / "body.html").read_text(encoding="utf-8")
    footer = "" if popup else (
        f'<footer><span data-i18n="footer">أسعار الذهب المباشرة في الإمارات:</span> {SITE_LINK}'
        ' · <a href="https://github.com/nbkdevs/uae-gold-prices">GitHub</a></footer>\n')
    head = ('<!doctype html>\n<html lang="ar" dir="rtl">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            '<title>حاسبة قيمة الذهب</title>\n')
    if not popup:
        head += ('<meta name="description" content="Free gold value calculator: 24/22/21/18/14K prices per gram, tola and ounce, '
                 'jewellery price with making charge and 5% VAT, and zakat on gold. Arabic and English.">\n')
    head += '<link rel="stylesheet" href="css/app.css">\n</head>\n'
    return (head + f'<body{" class=\"popup\"" if popup else ""}>\n' + body + footer +
            '<script src="js/gold.js"></script>\n<script src="js/app.js"></script>\n</body>\n</html>\n')


def main() -> None:
    (WEB / "js/gold.js").write_text(gold_js(), encoding="utf-8")
    targets = {ROOT / "packages/hf-space": "index.html", ROOT / "packages/docker/public": "index.html",
               ROOT / "extensions/shared": "popup.html"}
    for dest, name in targets.items():
        dest.mkdir(parents=True, exist_ok=True)
        for sub in ("css", "js"):
            shutil.rmtree(dest / sub, ignore_errors=True)
            shutil.copytree(WEB / sub, dest / sub)
        if name == "popup.html":
            # Store packages carry no site link: drop the library's header comment.
            js = gold_js()
            js = re.sub(r"/\*\*\n \* uae-gold-calculator:.*?\*/\n", "", js, count=1, flags=re.S)
            assert "uaegoldprices" not in js
            (dest / "js/gold.js").write_text(js, encoding="utf-8")
        (dest / name).write_text(page(popup=name == "popup.html"), encoding="utf-8")
        print(f"built {dest.relative_to(ROOT)}/{name}")


if __name__ == "__main__":
    main()
