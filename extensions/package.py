#!/usr/bin/env python3
"""Copy the shared popup into firefox/ and edge/, validate the manifests and zip everything into dist/.

The shared popup is generated by ../web/build.py (run that first after editing web/).
"""
from __future__ import annotations

import json
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SHARED = ROOT / "shared"
DIST = ROOT / "dist"
VERSION = "1.0.0"
SHARED_FILES = [
    "popup.html",
    "css/app.css",
    "js/gold.js",
    "js/app.js",
    "icons/icon16.png",
    "icons/icon32.png",
    "icons/icon48.png",
    "icons/icon128.png",
]


def zipdir(src: Path, zip_path: Path) -> Path:
    DIST.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(src.rglob("*")):
            if path.is_file() and path.name not in ("NOTES_FOR_CERTIFICATION.md",) and path.suffix not in (".zip", ".pak", ".py"):
                zf.write(path, path.relative_to(src).as_posix())
    return zip_path


def check_manifest(p: Path, browser: str) -> dict:
    m = json.loads(p.read_text(encoding="utf-8"))
    assert m["manifest_version"] == 3 and m["version"] == VERSION
    if browser != "theme":
        assert m["permissions"] == [], "extension must request no permissions"
        assert "host_permissions" not in m
        for n, rel in m["icons"].items():
            assert (p.parent / rel).is_file(), rel
        assert (p.parent / m["action"]["default_popup"]).is_file()
        html = (p.parent / "popup.html").read_text(encoding="utf-8")
        assert "http://" not in html and "https://" not in html, "popup must not link or load anything external"
        assert "onclick=" not in html and "<script>" not in html, "no inline script (CSP)"
    if browser == "firefox":
        g = m["browser_specific_settings"]["gecko"]
        assert g["id"] == "karat-gold-calculator@nbkdevs"
        assert g["data_collection_permissions"]["required"] == ["none"]
    for word in ("uae", "emirat", "uaegoldprices", "إمارات", "امارات"):
        assert word not in json.dumps(m, ensure_ascii=False).lower(), f"store item must not carry place/brand name: {word}"
    return m


def package_extension(browser: str) -> Path:
    dest = ROOT / browser
    for name in ("popup.html", "css", "js", "icons"):
        p = dest / name
        if p.is_file():
            p.unlink()
        elif p.is_dir():
            shutil.rmtree(p)
    for rel in SHARED_FILES:
        dst = dest / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(SHARED / rel, dst)
    check_manifest(dest / "manifest.json", browser)
    return zipdir(dest, DIST / f"karat-gold-calculator-{browser}-{VERSION}.zip")


def main() -> None:
    for browser in ("firefox", "edge"):
        path = package_extension(browser)
        print(f"{browser}: {path.relative_to(ROOT)} ({path.stat().st_size} bytes)")
    check_manifest(ROOT / "chrome-theme/manifest.json", "theme")
    theme = zipdir(ROOT / "chrome-theme", DIST / f"gilded-dune-chrome-theme-{VERSION}.zip")
    print(f"theme: {theme.relative_to(ROOT)} ({theme.stat().st_size} bytes)")
    print("manifests ok")


if __name__ == "__main__":
    main()
